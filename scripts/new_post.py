#!/usr/bin/env python3
"""Create a new bilingual post: Turkish and English pages plus the shared media folder.

    python scripts/new_post.py ENGLISH-SLUG [--tr-slug turkce-slug] [--type guide]
                               [--hugo PATH] [--no-cover]

Creates::

    content/tr/posts/<english-slug>/index.md        Turkish draft (from archetypes/posts.md)
    content/en/posts/<english-slug>/index.md        English draft, same date and postType
    content/media/posts/<english-slug>/img/         shared images
    content/media/posts/<english-slug>/credits.yaml
    content/media/posts/<english-slug>/feature.webp (scripts/make_covers.py)

The bundle name is the English slug: it pairs the two languages and is the EN
URL (``/en/posts/<english-slug>/``). The TR slug is the Turkish URL
(``/posts/<tr-slug>/``), an ASCII slug of the Turkish title; it never changes
once published. Both pages start as drafts with placeholders the linter rejects
until they are filled in.

Hugo is taken from ``--hugo``, the ``HUGO`` environment variable, or ``PATH``.
Exit codes: 0 created, 1 the bundle exists or Hugo failed, 2 usage error.
"""

from __future__ import annotations

import argparse
import logging
import re
import subprocess
import sys
from pathlib import Path

from common import (
    CONTENT_DIR,
    REPO_ROOT,
    ScriptError,
    add_logging_flags,
    author_name,
    find_hugo,
    setup_logging,
    write_text,
)

sys.path.insert(0, str(Path(__file__).resolve().parent / "images"))
from credits import save

log = logging.getLogger("new_post")

SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
POST_TYPES = ("project", "contribution", "guide", "story")


def valid_slug(value: str) -> str:
    if not SLUG.match(value) or not 3 <= len(value) <= 75:
        raise argparse.ArgumentTypeError(
            f"{value!r}: use lower-case ASCII words joined by hyphens, 3-75 characters"
        )
    return value


def create(slug: str, tr_slug: str | None, post_type: str, hugo: str, cover: bool) -> list[Path]:
    """Create the bundle in all three content trees. Returns the created paths."""
    for tree in ("tr", "en", "media"):
        if (CONTENT_DIR / tree / "posts" / slug).exists():
            raise ScriptError(f"bundle {slug} already exists in content/{tree}/posts")
    pages: dict[str, Path] = {}
    for lang in ("tr", "en"):
        rel = f"content/{lang}/posts/{slug}/index.md"
        try:
            subprocess.run(
                [hugo, "new", "content", rel], cwd=REPO_ROOT, check=True, stdout=subprocess.DEVNULL
            )
        except (OSError, subprocess.CalledProcessError) as exc:
            raise ScriptError(f"hugo new content {rel} failed: {exc}") from exc
        pages[lang] = REPO_ROOT / rel
    date = re.search(r"^date: (.+)$", pages["tr"].read_text(encoding="utf-8"), re.M)
    if not date:
        raise ScriptError("archetypes/posts.md produced no date")
    for lang, page in pages.items():
        text = page.read_text(encoding="utf-8")
        # Both languages share the same instant and post type.
        text = re.sub(r"^date: .+$", f"date: {date.group(1)}", text, count=1, flags=re.M)
        text = re.sub(r"^postType: .+$", f"postType: {post_type}", text, count=1, flags=re.M)
        if lang == "tr" and tr_slug:
            text = re.sub(r"^slug: .+$", f'slug: "{tr_slug}"', text, count=1, flags=re.M)
        write_text(page, text)
    media = CONTENT_DIR / "media" / "posts" / slug
    (media / "img").mkdir(parents=True, exist_ok=True)
    cover_entry = {
        "file": "feature.webp",
        "kind": "cover",
        "author": author_name(),
        "license": "own",
        "note": "Generated by scripts/make_covers.py from the bundle name and category.",
    }
    save(media / "credits.yaml", [cover_entry])
    created = [*pages.values(), media / "img", media / "credits.yaml"]
    if cover:
        result = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "make_covers.py"), slug],
            cwd=REPO_ROOT,
            check=False,
        )
        if result.returncode == 0:
            created.append(media / "feature.webp")
        else:
            log.warning("cover not generated; run scripts/make_covers.py %s later", slug)
    return created


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("slug", type=valid_slug, help="English slug = bundle name = EN URL")
    parser.add_argument(
        "--tr-slug", type=valid_slug, help="Turkish URL slug (ASCII form of the Turkish title)"
    )
    parser.add_argument(
        "--type", default="guide", choices=POST_TYPES, help="postType (default: %(default)s)"
    )
    parser.add_argument("--hugo", help="Hugo executable (default: $HUGO or hugo on PATH)")
    parser.add_argument("--no-cover", action="store_true", help="skip generating feature.webp")
    add_logging_flags(parser)
    args = parser.parse_args(argv)
    setup_logging(args.verbose, args.quiet)
    try:
        paths = create(args.slug, args.tr_slug, args.type, find_hugo(args.hugo), not args.no_cover)
    except ScriptError as exc:
        log.error("%s", exc)
        return 1
    for path in paths:
        log.info("created %s", path.relative_to(REPO_ROOT).as_posix())
    if not args.tr_slug:
        log.info("set the Turkish slug in content/tr/posts/%s/index.md", args.slug)
    return 0


if __name__ == "__main__":
    sys.exit(main())
